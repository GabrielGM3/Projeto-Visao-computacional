def exportar_mapeamento_por_classe(
    split_json_path="docs/data_split.json",
    output_json_path="docs/mapeamento_classes_objetivo.json"
):

    #Lê o split oficial e cria um JSON estruturado explicitamente por:
    #Classe -> Objetivo (treino, validacao, teste) -> Lista de caminhos + contagem. */

    if not os.path.exists(split_json_path):
        raise FileNotFoundError(f"Arquivo de split não encontrado em {split_json_path}. Rode a divisão primeiro.")

    with open(split_json_path, "r", encoding="utf-8") as f:
        dados = json.load(f)

    classes = list(dados["class_to_idx"].keys())

    # Inicializa a estrutura hierárquica
    mapeamento = {
        classe: {
            "id_classe": dados["class_to_idx"][classe],
            "resumo_quantidades": {"treino": 0, "validacao": 0, "teste": 0, "total": 0},
            "objetivos": {
                "treino": [],
                "validacao": [],
                "teste": []
            }
        }
        for classe in classes
    }

    # Distribui cada caminho na sua respectiva classe e objetivo
    for objetivo in ["treino", "validacao", "teste"]:
        for rel_path in dados[objetivo]:
            classe_nome = rel_path.split('/')[0]
            mapeamento[classe_nome]["objetivos"][objetivo].append(rel_path)

    # Atualiza as contagens exatas para auditoria rápida
    for classe in classes:
        qtd_tr = len(mapeamento[classe]["objetivos"]["treino"])
        qtd_va = len(mapeamento[classe]["objetivos"]["validacao"])
        qtd_te = len(mapeamento[classe]["objetivos"]["teste"])
        mapeamento[classe]["resumo_quantidades"] = {
            "treino": qtd_tr,
            "validacao": qtd_va,
            "teste": qtd_te,
            "total": qtd_tr + qtd_va + qtd_te
        }

    os.makedirs(os.path.dirname(output_json_path), exist_ok=True)
    with open(output_json_path, "w", encoding="utf-8") as f:
        json.dump(mapeamento, f, indent=4)

    print(f"[SUCESSO] Mapeamento hierárquico (Classe + Objetivo) salvo em: {output_json_path}")
    return mapeamento



