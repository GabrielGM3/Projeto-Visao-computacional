class EuroSATSubset(Dataset):
    """
    Classe Dataset isolada para cada partição (Treino, Validação ou Teste).
    Permite que cada split receba suas próprias transformações no futuro
    sem causar vazamento de dados (data leakage) entre treino e teste.
    """
    def __init__(self, root_dir, rel_paths, class_to_idx, transform=None):
        self.root_dir = root_dir
        self.rel_paths = rel_paths
        self.class_to_idx = class_to_idx
        self.classes = sorted(class_to_idx, key=class_to_idx.get)
        self.transform = transform

        self.samples = []
        for rel_path in self.rel_paths:
            classe_nome = rel_path.split('/')[0]
            idx = self.class_to_idx[classe_nome]
            full_path = os.path.join(self.root_dir, rel_path.replace('/', os.sep))
            self.samples.append((full_path, idx))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        path, target = self.samples[idx]
        with Image.open(path) as img:
            img = img.convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img, target


def verificar_integridade_imagens(dataset_base):

    #Sanity check: verifica se há imagens corrompidas ou ilegíveis na base.

    print("Iniciando verificação de integridade (Sanity Check)...")
    corrompidas = []
    for path, _ in dataset_base.samples:
        try:
            with Image.open(path) as img:
                img.verify()
        except Exception as e:
            corrompidas.append((path, str(e)))

    if corrompidas:
        print(f"[ERRO CRÍTICO] {len(corrompidas)} imagens corrompidas encontradas:")
        for p, err in corrompidas:
            print(f" - {p}: {err}")
        raise RuntimeError("Corrija ou remova as imagens corrompidas antes de prosseguir.")
    else:
        print("OK: Todas as imagens estão íntegras.\n")


def gerar_ou_carregar_split(
    data_dir,
    split_json_path="docs/data_split.json",
    train_ratio=0.70,
    val_ratio=0.15,
    test_ratio=0.15,
    seed=42,
    forcar_recriacao=False
):

    #Gera a divisão e salva em JSON.

    if round(train_ratio + val_ratio + test_ratio, 5) != 1.0:
        raise ValueError("As proporções de treino, validação e teste devem somar 1.0.")

    if os.path.exists(split_json_path) and not forcar_recriacao:
        print(f"Carregando divisão fixa existente de: {split_json_path}\n")
        with open(split_json_path, "r", encoding="utf-8") as f:
            return json.load(f)

    dataset_base = datasets.ImageFolder(root=data_dir)
    verificar_integridade_imagens(dataset_base)

    class_to_idx = dataset_base.class_to_idx
    classes = dataset_base.classes

    arquivos_por_classe = {c: [] for c in classes}
    for full_path, idx in dataset_base.samples:
        classe_nome = classes[idx]
        rel_path = os.path.relpath(full_path, data_dir).replace(os.sep, '/')
        arquivos_por_classe[classe_nome].append(rel_path)

    rng = random.Random(seed)
    treino_paths, val_paths, teste_paths = [], [], []

    for classe in classes:
        caminhos = sorted(arquivos_por_classe[classe])
        rng.shuffle(caminhos)

        total_c = len(caminhos)
        n_treino = int(total_c * train_ratio)
        n_val = int(total_c * val_ratio)

        treino_paths.extend(caminhos[:n_treino])
        val_paths.extend(caminhos[n_treino:n_treino + n_val])
        teste_paths.extend(caminhos[n_treino + n_val:])

    dados_split = {
        "seed": seed,
        "ratios": {"train": train_ratio, "val": val_ratio, "test": test_ratio},
        "class_to_idx": class_to_idx,
        "treino": treino_paths,
        "validacao": val_paths,
        "teste": teste_paths
    }

    os.makedirs(os.path.dirname(split_json_path), exist_ok=True)
    with open(split_json_path, "w", encoding="utf-8") as f:
        json.dump(dados_split, f, indent=4)

    print(f"Divisão estratificada salva em: {split_json_path}\n")
    return dados_split


